/** Generates docs/03-architecture/data-classification-register.md from the classification map. */
import { writeFileSync } from 'node:fs';
import { CLASSIFICATION } from '../src/db/classification.js';

const rows = Object.entries(CLASSIFICATION).sort(([a], [b]) => a.localeCompare(b));
const personal = rows.filter(([, c]) => c === 'personal' || c === 'sensitive_personal');
const md = `# Data Classification Register

> Generated by \`npm run pii-register\` from \`backend/src/db/classification.ts\`. Do not edit by hand.
> CI fails if a column exists that is not listed here (FR-PRV-01, US-110).

## Personal data held (${personal.length} columns)
| Column | Class |
|---|---|
${personal.map(([k, c]) => `| \`${k}\` | ${c} |`).join('\n')}

No **Sensitive-Personal** data (government IDs, bank accounts, salary) exists yet; those arrive with HCM (M5) and require
field-level encryption (US-111) first. See [ADR-005](adr/ADR-005-privacy-by-design.md).

## All columns
| Column | Class |
|---|---|
${rows.map(([k, c]) => `| \`${k}\` | ${c} |`).join('\n')}
`;
writeFileSync(new URL('../../docs/03-architecture/data-classification-register.md', import.meta.url), md);
console.log(`wrote register: ${rows.length} columns, ${personal.length} personal`);
